#!/usr/bin/env python3
"""sym_forest_sat.py -- exact search (SAT + lazy cycle cuts) for an induced forest F of Q_d with |F| >= K
that is invariant under a group G of automorphisms of Q_d generated by the given generators.

An automorphism is written  perm:t  where perm is a permutation of 0..d-1 given as d digits/comma list
(coordinate i of x goes to coordinate perm[i]) and t is an integer (bit mask) XORed afterwards:
   g(x) = P(x) XOR t.   Every such map is an automorphism of Q_d (it maps vertices differing in coordinate i
to vertices differing in coordinate perm[i]).

Variables: one boolean per G-orbit ("the orbit is contained in F").  A G-invariant F is exactly a union of
orbits, so this is a complete encoding of the class {G-invariant F}.
Constraints:
  * weighted cardinality: sum_{orbits O} |O| x_O >= K  (totalizer over the list in which x_O is repeated |O|
    times; tested on small cases, see README);
  * for every 4-cycle and every induced 6-cycle of Q_d (all of them, listed explicitly): not all its orbits
    in F;
  * lazily: whenever the SAT model's F contains a cycle, the clause "not all orbits of this cycle in F" is
    added (a cycle found by BFS shortest path between the ends of a non-forest edge), and we re-solve.
Every clause excludes only sets F that contain a cycle, so it is valid for all induced forests.
The loop ends with SAT (an F with no cycle, verified independently by union-find: printed and written)
or UNSAT (no G-invariant induced forest of size >= K exists).
Usage: sym_forest_sat.py d K gen1 [gen2 ...] [--out file] [--solver cadical153] [--maxit N]
"""
import sys, time, itertools
from collections import deque
from pysat.solvers import Solver
from pysat.card import CardEnc, EncType


def parse_gen(s, d):
    p, t = s.split(":")
    perm = [int(c) for c in (p.split(",") if "," in p else list(p))]
    assert sorted(perm) == list(range(d)), s
    return perm, int(t)


def apply(g, x, d):
    perm, t = g
    y = 0
    for i in range(d):
        if (x >> i) & 1:
            y |= 1 << perm[i]
    return y ^ t


def orbits_of(gens, d):
    n = 1 << d
    orb = [-1] * n
    orbs = []
    for x in range(n):
        if orb[x] >= 0:
            continue
        k = len(orbs)
        orb[x] = k
        cur = [x]
        q = [x]
        while q:
            y = q.pop()
            for g in gens:
                z = apply(g, y, d)
                if orb[z] < 0:
                    orb[z] = k
                    cur.append(z)
                    q.append(z)
        orbs.append(cur)
    return orb, orbs


def is_forest(F, d):
    n = 1 << d
    par = list(range(n))

    def find(a):
        while par[a] != a:
            par[a] = par[par[a]]
            a = par[a]
        return a
    for v in range(n):
        if F[v]:
            for j in range(d):
                w = v ^ (1 << j)
                if w > v and F[w]:
                    a, b = find(v), find(w)
                    if a == b:
                        return False
                    par[a] = b
    return True


def find_cycles(F, d, limit):
    """Return up to `limit` cycles (vertex lists) of G[F]: for each edge closing a cycle in a union-find
    sweep, the shortest path between its ends avoiding that edge."""
    n = 1 << d
    par = list(range(n))

    def find(a):
        while par[a] != a:
            par[a] = par[par[a]]
            a = par[a]
        return a
    cyc = []
    for v in range(n):
        if not F[v]:
            continue
        for j in range(d):
            w = v ^ (1 << j)
            if w > v and F[w]:
                a, b = find(v), find(w)
                if a != b:
                    par[a] = b
                    continue
                # BFS from v to w in G[F] avoiding edge (v,w)
                prev = {v: -1}
                dq = deque([v])
                while dq:
                    x = dq.popleft()
                    if x == w:
                        break
                    for jj in range(d):
                        y = x ^ (1 << jj)
                        if F[y] and y not in prev and not (x == v and y == w):
                            prev[y] = x
                            dq.append(y)
                path = []
                x = w
                while x != -1:
                    path.append(x)
                    x = prev[x]
                cyc.append(path)
                if len(cyc) >= limit:
                    return cyc
    return cyc


def main():
    args = sys.argv[1:]
    out = None
    solver = "cadical153"
    maxit = 10 ** 9
    rest = []
    i = 0
    while i < len(args):
        if args[i] == "--out":
            out = args[i + 1]; i += 2
        elif args[i] == "--solver":
            solver = args[i + 1]; i += 2
        elif args[i] == "--maxit":
            maxit = int(args[i + 1]); i += 2
        else:
            rest.append(args[i]); i += 1
    d, K = int(rest[0]), int(rest[1])
    gens = [parse_gen(s, d) for s in rest[2:]]
    n = 1 << d
    orb, orbs = orbits_of(gens, d)
    m = len(orbs)
    sizes = [len(o) for o in orbs]
    print("d=%d K=%d gens=%s orbits=%d size-profile=%s" % (d, K, rest[2:], m,
          sorted({s: sizes.count(s) for s in sizes}.items())), flush=True)
    t0 = time.time()
    clauses = set()

    def cut(vs):
        c = tuple(sorted({orb[v] + 1 for v in vs}))
        return c
    # 4-cycles: faces {x, x^ei, x^ej, x^ei^ej}
    for x in range(n):
        for a in range(d):
            for b in range(a + 1, d):
                if not (x >> a) & 1 and not (x >> b) & 1:
                    clauses.add(cut([x, x ^ (1 << a), x ^ (1 << b), x ^ (1 << a) ^ (1 << b)]))
    # induced 6-cycles: in each 3-subcube, the 6 vertices other than an antipodal pair
    for x in range(n):
        for a, b, c in itertools.combinations(range(d), 3):
            if (x >> a) & 1 or (x >> b) & 1 or (x >> c) & 1:
                continue
            cube = [x ^ (((s >> 0) & 1) << a) ^ (((s >> 1) & 1) << b) ^ (((s >> 2) & 1) << c) for s in range(8)]
            for s in range(4):
                six = [cube[r] for r in range(8) if r != s and r != 7 - s]
                clauses.add(cut(six))
    S = Solver(name=solver)
    for c in clauses:
        S.add_clause([-l for l in c])
    lits = []
    for k in range(m):
        lits += [k + 1] * sizes[k]
    card = CardEnc.atleast(lits=lits, bound=K, top_id=m, encoding=EncType.totalizer)
    for c in card.clauses:
        S.add_clause(c)
    print("initial short-cycle clauses: %d, card clauses: %d, setup %.1fs" % (len(clauses), len(card.clauses),
          time.time() - t0), flush=True)
    it = 0
    ncuts = 0
    while it < maxit:
        it += 1
        if not S.solve():
            print("UNSAT after %d iterations, %d lazy cuts, %.1fs: no G-invariant induced forest with |F| >= %d"
                  % (it, ncuts, time.time() - t0, K), flush=True)
            return
        model = S.get_model()
        chosen = [k for k in range(m) if model[k] > 0]
        F = [0] * n
        for k in chosen:
            for v in orbs[k]:
                F[v] = 1
        cycles = find_cycles(F, d, 400)
        if not cycles:
            assert is_forest(F, d)
            sz = sum(F)
            print("SAT after %d iterations, %d lazy cuts, %.1fs: forest |F|=%d |S|=%d" % (it, ncuts,
                  time.time() - t0, sz, n - sz), flush=True)
            if out:
                with open(out, "w") as fh:
                    fh.write("".join(str(F[v]) for v in range(n)) + "\n")
            return
        new = 0
        for cy in cycles:
            c = cut(cy)
            if c not in clauses:
                clauses.add(c)
                S.add_clause([-l for l in c])
                new += 1
        ncuts += new
        if it % 20 == 0:
            print("  it %d cuts %d (last batch %d) %.1fs" % (it, ncuts, new, time.time() - t0), flush=True)
        if new == 0:
            print("ERROR: no new cut", flush=True)
            return
    print("STOPPED at maxit=%d (%d cuts, %.1fs), undecided" % (maxit, ncuts, time.time() - t0), flush=True)


if __name__ == "__main__":
    main()
