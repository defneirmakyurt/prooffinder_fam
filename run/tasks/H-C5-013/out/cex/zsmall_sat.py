"""Exact SAT/CEGAR check of the Theorem (proof.md Step 8/9) for |O \\ F| = z <= 3.
For a fixed set Z of z odd vertices, F = (O \\ Z) u M with M a subset of E (variables x_v, v in E).
Question: is there M with |M| >= k and Q_9[F] acyclic?  |F| = 256 - z + |M|, so |F| >= 280 <=> |M| >= 24 + z.
Clauses: (a) 4-cycles: for x, x' in E at distance 2 whose two common neighbours are both outside Z: (-x v -x').
         (b) lazily, any cycle found in a SAT model: clause "not all even vertices of the cycle in M"
             (the odd vertices of the cycle lie in O \\ Z, which is always in F, so the clause is sound).
UNSAT at k  <=>  no induced forest with this Z and |M| >= k.
Configurations Z are taken up to automorphisms of Q_9 that fix the parity classes (see orbit_reps()).
Usage: python zsmall_sat.py <z> <extra>   (k = 24 + z - extra;  extra = 0 tests |F| >= 280) [timeout_s]"""
import sys, time, itertools
from pysat.solvers import Cadical153
from pysat.card import CardEnc, EncType
from common import *

def orbit_reps(z):
    """Representatives of 3-, 2-, 1-, 0-subsets Z of O under the group generated by coordinate permutations
    and even translations (both preserve E and O).  A z-set {o_1..o_z} is described by its 9 columns
    (o_1j,..,o_zj) in {0,1}^z; translation complements whole columns, permutation permutes columns.
    Hence the orbit (with the points unordered) is determined by the multiset of columns up to complement,
    up to relabelling of the points.  We enumerate ALL z-subsets containing o_1 = e_1 (even translations act
    transitively on O, so every orbit meets this family) and keep one per canonical form.  Returns reps and
    the number of subsets canonicalised."""
    if z == 0:
        return [()], 1
    o1 = 1
    others = [o for o in ODD if o != o1]
    reps = {}
    cnt = 0
    for rest in itertools.combinations(others, z - 1):
        pts = (o1,) + rest
        cnt += 1
        best = None
        for perm in itertools.permutations(pts):
            cols = []
            for j in range(D):
                c = tuple((p >> j) & 1 for p in perm)
                if c[0] == 1:
                    c = tuple(1 - b for b in c)   # normalise complement
                cols.append(c)
            key = tuple(sorted(cols))
            if best is None or key < best:
                best = key
        if best not in reps:
            reps[best] = pts
    return list(reps.values()), cnt

def solve(Z, k, timeout):
    Zs = set(Z)
    idx = {v: i + 1 for i, v in enumerate(EVEN)}
    clauses = []
    for a in EVEN:
        for i in range(D):
            for j in range(i + 1, D):
                b = a ^ (1 << i) ^ (1 << j)
                if b < a: continue
                c1, c2 = a ^ (1 << i), a ^ (1 << j)
                if c1 not in Zs and c2 not in Zs:
                    clauses.append([-idx[a], -idx[b]])
    card = CardEnc.atleast(lits=list(idx.values()), bound=k, top_id=len(EVEN), encoding=EncType.seqcounter)
    s = Cadical153(bootstrap_with=clauses + card.clauses)
    t0 = time.time()
    iters = 0
    base = set(o for o in ODD if o not in Zs)
    while True:
        if time.time() - t0 > timeout:
            return "TIMEOUT", iters, None
        ok = s.solve()
        iters += 1
        if not ok:
            return "UNSAT", iters, None
        model = s.get_model()
        M = [v for v in EVEN if model[idx[v] - 1] > 0]
        F = base | set(M)
        cyc = find_cycle(F)
        if cyc is None:
            assert is_forest(F)
            return "SAT", iters, sorted(M)
        s.add_clause([-idx[v] for v in cyc if wt(v) % 2 == 0])

if __name__ == "__main__":
    z = int(sys.argv[1]); extra = int(sys.argv[2]); timeout = float(sys.argv[3]) if len(sys.argv) > 3 else 300
    reps, cnt = orbit_reps(z)
    k = 24 + z - extra
    print("z=%d: %d z-subsets containing e_1 canonicalised, %d orbit representatives; testing |M| >= %d (|F| >= %d)"
          % (z, cnt, len(reps), k, 256 - z + k), flush=True)
    T0 = time.time()
    for Z in reps:
        t0 = time.time()
        st, it, M = solve(Z, k, timeout)
        dists = [wt(a ^ b) for a, b in itertools.combinations(Z, 2)]
        print("  Z=%s pairwise dists=%s -> %s (%d SAT calls, %.1fs)%s" % (
            [format(o, "09b") for o in Z], dists, st, it, time.time() - t0,
            "" if M is None else " M=%s" % [format(v, "09b") for v in M]), flush=True)
    print("total %.1fs" % (time.time() - T0))
